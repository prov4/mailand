package store

import (
	"context"
	"database/sql"
	"errors"
)

// Folder mirrors the folders table.
type Folder struct {
	ID            string // generated by UpsertFolder if empty
	AccountID     string
	Name          string
	Path          string // IMAP mailbox path or Gmail label name; unique per account
	Kind          string // "folder" | "gmail_label"; defaults to "folder"
	SpecialUse    string // e.g. `\Inbox`, `\All`; "" = none
	IsSyncSource  bool
	UIDValidity   int64
	LastSyncedUID int64
	HighestModSeq int64
	UnreadCount   int // maintained by the store; ignored on upsert
}

const folderCols = `id, account_id, name, path, kind, COALESCE(special_use,''), is_sync_source,
  COALESCE(uid_validity,0), COALESCE(last_synced_uid,0), COALESCE(highest_modseq,0), COALESCE(unread_count,0)`

func scanFolder(sc interface{ Scan(...any) error }) (Folder, error) {
	var f Folder
	var src int
	err := sc.Scan(&f.ID, &f.AccountID, &f.Name, &f.Path, &f.Kind, &f.SpecialUse, &src,
		&f.UIDValidity, &f.LastSyncedUID, &f.HighestModSeq, &f.UnreadCount)
	f.IsSyncSource = src != 0
	return f, err
}

// UpsertFolder inserts or updates a folder keyed by (AccountID, Path) and
// returns the stored folder with its stable ID (the existing ID wins over
// f.ID on update). Sync state and unread count are never overwritten here;
// use UpdateFolderSyncState.
func (s *Store) UpsertFolder(ctx context.Context, f Folder) (Folder, error) {
	if f.ID == "" {
		f.ID = newID()
	}
	if f.Kind == "" {
		f.Kind = "folder"
	}
	var id string
	err := s.db.QueryRowContext(ctx, `
INSERT INTO folders (id, account_id, name, path, kind, special_use, is_sync_source, uid_validity, last_synced_uid, highest_modseq)
VALUES (?,?,?,?,?,?,?,?,?,?)
ON CONFLICT(account_id, path) DO UPDATE SET name=excluded.name, kind=excluded.kind,
  special_use=excluded.special_use, is_sync_source=excluded.is_sync_source
RETURNING id`,
		f.ID, f.AccountID, f.Name, f.Path, f.Kind, nullStr(f.SpecialUse), b2i(f.IsSyncSource),
		f.UIDValidity, f.LastSyncedUID, f.HighestModSeq).Scan(&id)
	if err != nil {
		return Folder{}, err
	}
	return s.GetFolder(ctx, id)
}

// ListFolders returns an account's folders ordered by path.
func (s *Store) ListFolders(ctx context.Context, accountID string) ([]Folder, error) {
	rows, err := s.db.QueryContext(ctx, `SELECT `+folderCols+` FROM folders WHERE account_id=? ORDER BY path`, accountID)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []Folder
	for rows.Next() {
		f, err := scanFolder(rows)
		if err != nil {
			return nil, err
		}
		out = append(out, f)
	}
	return out, rows.Err()
}

// GetFolder returns ErrNotFound if missing.
func (s *Store) GetFolder(ctx context.Context, id string) (Folder, error) {
	f, err := scanFolder(s.db.QueryRowContext(ctx, `SELECT `+folderCols+` FROM folders WHERE id=?`, id))
	if errors.Is(err, sql.ErrNoRows) {
		return f, ErrNotFound
	}
	return f, err
}

// UpdateFolderSyncState records IMAP sync progress for a folder.
func (s *Store) UpdateFolderSyncState(ctx context.Context, folderID string, uidValidity, lastSyncedUID, highestModSeq int64) error {
	res, err := s.db.ExecContext(ctx,
		`UPDATE folders SET uid_validity=?, last_synced_uid=?, highest_modseq=? WHERE id=?`,
		uidValidity, lastSyncedUID, highestModSeq, folderID)
	return affected(res, err)
}

// DeleteFolder removes the folder, its memberships, and every message whose
// source mailbox it is. Unread counts of other folders are fixed up.
func (s *Store) DeleteFolder(ctx context.Context, id string) error {
	return s.inTx(ctx, func(tx *sql.Tx) error {
		other, err := foldersOfSourceMessages(ctx, tx, id)
		if err != nil {
			return err
		}
		if _, err := tx.ExecContext(ctx, `DELETE FROM folders WHERE id=?`, id); err != nil {
			return err
		}
		return recomputeUnread(ctx, tx, other)
	})
}

// ClearFolderMessages deletes all messages whose source mailbox is folderID and
// resets its sync state. Use when UIDVALIDITY changes.
func (s *Store) ClearFolderMessages(ctx context.Context, folderID string) error {
	return s.inTx(ctx, func(tx *sql.Tx) error {
		affectedF, err := foldersOfSourceMessages(ctx, tx, folderID)
		if err != nil {
			return err
		}
		if _, err := tx.ExecContext(ctx, `DELETE FROM messages WHERE folder_id=?`, folderID); err != nil {
			return err
		}
		if _, err := tx.ExecContext(ctx, `UPDATE folders SET last_synced_uid=0, highest_modseq=0 WHERE id=?`, folderID); err != nil {
			return err
		}
		return recomputeUnread(ctx, tx, affectedF)
	})
}

func affected(res sql.Result, err error) error {
	if err != nil {
		return err
	}
	if n, _ := res.RowsAffected(); n == 0 {
		return ErrNotFound
	}
	return nil
}

// foldersOfSourceMessages lists every folder that has a membership row for a
// message whose source folder is folderID (including folderID itself).
func foldersOfSourceMessages(ctx context.Context, q execer, folderID string) ([]string, error) {
	return queryStrings(ctx, q, `
SELECT DISTINCT mf.folder_id FROM message_folders mf
JOIN messages m ON m.seq = mf.message_seq WHERE m.folder_id = ?`, folderID)
}

func queryStrings(ctx context.Context, q execer, query string, args ...any) ([]string, error) {
	rows, err := q.QueryContext(ctx, query, args...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []string
	for rows.Next() {
		var s string
		if err := rows.Scan(&s); err != nil {
			return nil, err
		}
		out = append(out, s)
	}
	return out, rows.Err()
}

// recomputeUnread sets unread_count for the given folders from the source of truth.
func recomputeUnread(ctx context.Context, q execer, folderIDs []string) error {
	seen := map[string]bool{}
	for _, id := range folderIDs {
		if seen[id] {
			continue
		}
		seen[id] = true
		if _, err := q.ExecContext(ctx, `
UPDATE folders SET unread_count = (
  SELECT COUNT(*) FROM message_folders mf JOIN messages m ON m.seq = mf.message_seq
  WHERE mf.folder_id = folders.id AND m.is_read = 0) WHERE id = ?`, id); err != nil {
			return err
		}
	}
	return nil
}
